use std::assert_eq;

use hot_springs::*;
use utility::test_case_n;

test_case_n!(example1, "
???.### 1,1,3
.??..??...?##. 1,1,3
?#?#?#?#?#?#?#? 1,3,1,6
????.#...#... 4,1,1
????.######..#####. 1,6,5
?###???????? 3,2,1",
    part1: (part1::solve, 21),
    part2: (part2::solve, 525152)
);

#[test]
fn example_part1() {
    for (ans, line) in [
        (1, "???.### 1,1,3"),
        (4, ".??..??...?##. 1,1,3"),
        (1, "?#?#?#?#?#?#?#? 1,3,1,6"),
        (1, "????.#...#... 4,1,1"),
        (4, "????.######..#####. 1,6,5"),
        (10, "?###???????? 3,2,1"),
    ] {
        assert_eq!(part1::solve(line.to_string()), ans);
    }
}

#[test]
fn example_part2() {
    for (ans, line) in [
        (1, "???.### 1,1,3"),
        (16384, ".??..??...?##. 1,1,3"),
        (1, "?#?#?#?#?#?#?#? 1,3,1,6"),
        (16, "????.#...#... 4,1,1"),
        (2500, "????.######..#####. 1,6,5"),
        (506250, "?###???????? 3,2,1"),
    ] {
        assert_eq!(part2::solve(line.to_string()), ans);
    }
}