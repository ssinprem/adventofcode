use std::assert_eq;

use hot_springs::*;
use utility::test_case_n;

test_case_n!(example1, "
???.### 1,1,3
.??..??...?##. 1,1,3
?#?#?#?#?#?#?#? 1,3,1,6
????.#...#... 4,1,1
????.######..#####. 1,6,5
?###???????? 3,2,1",
    part1: (part1::solve, 21)
);

#[test]
fn example() {
    for (ans, line) in [
        (1, "???.### 1,1,3"),
        (4, ".??..??...?##. 1,1,3"),
        (1, "?#?#?#?#?#?#?#? 1,3,1,6"),
        (1, "????.#...#... 4,1,1"),
        (4, "????.######..#####. 1,6,5"),
        (10, "?###???????? 3,2,1"),
    ] {
        assert_eq!(part1::solve(line.to_string()), ans);
    }
}
